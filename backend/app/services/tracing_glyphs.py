"""Tracés de référence des lettres et chiffres pour l'exercice ``tracing``.

Chaque glyphe est une suite **ordonnée** de traits, chaque trait une polyligne
parcourue **dans le sens enseigné** : l'ordre et le sens sont corrigés en mode
guidé, ils font donc partie de la donnée.

Repère commun : une case de 100 × 140, y vers le bas.

- ``capitale`` et ``chiffre`` : haut à y=10, ligne médiane à y=70, base à y=130.
- ``script`` et ``cursive`` (minuscules, lignage type Seyès) : hampes à y=10,
  ligne d'écriture (hauteur d'x) à y=50, ligne de base à y=90, jambages à y=130.

Les capitales viennent du prototype « Ardoise des lettres » de Thomas.
"""

