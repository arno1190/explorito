def arc(cx: float, cy: float, rx: float, ry: float, a0: float, a1: float) -> Stroke:
    """Arc d'ellipse de ``a0`` à ``a1`` degrés (0 = droite, 90 = bas, sens croissant = horaire à l'écran)."""
    n = max(16, round(abs(a1 - a0) / 5))
    return [
        (
            cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
            cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / n)),
        )
        for i in range(n + 1)
    ]


def curve(start: Point, *segments: tuple[Point, Point, Point]) -> Stroke:
    """Chaîne de Bézier cubiques : chaque segment donne (contrôle 1, contrôle 2, arrivée)."""
    points: Stroke = [start]
    p0 = start
    for c1, c2, p1 in segments:
        for i in range(1, 25):
            t = i / 24
            u = 1 - t
            points.append(
                (
                    u**3 * p0[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t**3 * p1[0],
                    u**3 * p0[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t**3 * p1[1],
                )
            )
        p0 = p1
    return points


def join(*parts: Stroke) -> Stroke:
    """Concatène des morceaux en un seul trait continu."""
    out: Stroke = []
    for part in parts:
        out.extend(part)
    return out


def _dot(x: float, y: float) -> Stroke:
    return [(x, y), (x + 0.5, y + 0.5)]


